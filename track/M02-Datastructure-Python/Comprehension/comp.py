print("-----sorted function-----")
marks = [60,73,48,50]
new_marks = sorted(marks)
print(new_marks)
print(marks)

print("-----sorted in decending order-----")
marks = [60,73,48,50]
new_marks = sorted(marks,reverse = True)
print(new_marks)
print(marks)

